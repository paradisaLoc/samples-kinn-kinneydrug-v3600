@WIZRPL(SQLQUERY=SELECT DISTINCT OBJ.F01,ALT.F154,
	 ISNULL(PRI.F2668,'') AS PromoCode
	,'' AS PromoDesc
	,Promo.PromoType as PromoType
	,PRI.F137 AS PromoStartDte
	,DATEADD(dd,1,GETDATE()) as PromoEndDte
	,CASE 
	  WHEN Promo.PromoType='SingleDeal' THEN PRI.F139 
	  WHEN Promo.PromoType='MultiDeal'  THEN PRI.F136 
	  ELSE '' END as FixedPrice
	,'False' as IsDeleted
	,(SELECT DISTINCT STORE.F1056 AS CODE FROM LNK_TAB STORE WHERE F1000=PRI.F1000 FOR XML AUTO) as Stores
	,CASE 
	  WHEN Promo.PromoType='TPRForBG' AND CHARINDEX('M',ECL.F33)>0 THEN 'GET' 
	  ELSE 'BUY' END as PGGroupType
	,ISNULL(ECL.IntGrpCode,1) as IntGrpCode
	,CASE 
	  WHEN Promo.PromoType='TPRForBG' THEN -9999 
	  WHEN Promo.PromoType='MultiDeal' THEN -9999
	  ELSE PRI.F30 END as NonPromoRepPrice
	,CASE 
	  WHEN Promo.PromoType='SingleDeal' THEN PRI.F143 
	  WHEN Promo.PromoType='MultiDeal'  THEN ECL.F64 
	  WHEN Promo.PromoType='TPRForBG' THEN ECL.F64 
	  ELSE PRI.F135 END as PGQty
	,CASE 
	  WHEN ISNULL(PRI.F1221,0)>0 THEN -9999
	  WHEN ISNULL(PRI.F1220,0)>0 THEN -9999
	  WHEN Promo.PromoType='TPRForBG' THEN -9999
	  WHEN Promo.PromoType='MultiDeal' THEN -9999
	  ELSE PRI.F136 END as PromoRepPrice
	,CASE 
	  WHEN ISNULL(PRI.F1221,0)>0 THEN PRI.F1221 
	  ELSE -9999 END as PGPcOff
	,CASE 
	  WHEN Promo.PromoType!='TPRForBG' AND ISNULL(PRI.F1220,0)>0 THEN PRI.F1220 
	  WHEN Promo.PromoType='TPRForBG'  AND ISNULL(PRI.F136,0)>0  THEN PRI.F136 
	  ELSE -9999 END as PGAmtOff
	,CASE 
	  WHEN Promo.PromoType='TPRForBG' THEN ISNULL(SUBALT.F154,SUBPRI.F01) 
	  ELSE ISNULL(ALT.F154,PRI.F01) END as MainCode
	,CASE 
	  WHEN Promo.PromoType='TPRForBG' THEN SUBPRI.F136 
	  ELSE '' END as PromoPrice
	,CASE 
	  WHEN Promo.PromoType='TPRForBG' THEN SUBPRI.F30 
	  ELSE '' END as NonPromoPrice
FROM PRICE_TAB PRI
JOIN (SELECT PRICE_TAB.F126,PRICE_TAB.F1000,PRICE_TAB.F01,
CASE 
  WHEN ISNULL(POS_TAB.F110,0)=0 AND ISNULL(PRICE_TAB.F143,0)!=0 THEN 'SingleDeal' 
  WHEN ISNULL(POS_TAB.F110,0)=1 AND CHARINDEX('CB',ISNULL(PRICE_TAB.F146,''))>0 THEN 'MultiDeal'
  WHEN ISNULL(POS_TAB.F110,0)=1 AND CHARINDEX('CB',ISNULL(PRICE_TAB.F146,''))=0 THEN 'TPRForBG'
  ELSE 'TPR' END AS PromoType
FROM PRICE_TAB JOIN POS_TAB ON POS_TAB.F01=PRICE_TAB.F01
WHERE ISNULL(PRICE_TAB.F136,0)!=0) Promo ON Promo.F01=PRI.F01 AND Promo.F126=PRI.F126 AND Promo.F1000=PRI.F1000
JOIN OBJ_TAB OBJ ON OBJ.F01=PRI.F01
LEFT OUTER JOIN ALT_TAB ALT ON ALT.F01=OBJ.F01
JOIN POS_TAB POS ON POS.F01=OBJ.F01
LEFT OUTER JOIN (SELECT ROW_NUMBER() OVER (PARTITION BY F164 ORDER BY CHARINDEX('M',F33)) AS IntGrpCode,* FROM ECL_TAB WHERE F1033='PID' OR F1033='ITM') ECL ON ECL.F164=OBJ.F01
LEFT OUTER JOIN POS_TAB SUBPOS ON (SUBPOS.F01=ECL.F01 AND ECL.F1033='ITM') OR (','+(SUBPOS.F383)+',' LIKE '%,'+ECL.F01 + ',%' AND ECL.F1033='PID')
LEFT OUTER JOIN PRICE_TAB SUBPRI ON SUBPRI.F01=SUBPOS.F01
LEFT OUTER JOIN ALT_TAB SUBALT ON SUBALT.F01=SUBPRI.F01
WHERE ISNULL(PRI.F2668,'')!=''
ORDER BY PromoType,PromoCode,PGGroupType,MainCode);

