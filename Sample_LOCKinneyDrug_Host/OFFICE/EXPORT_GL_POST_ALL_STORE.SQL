@FMT(CMP,@WIZEXIST(BATCH_FILENAME)=1,®WIZRPL(SCHEDULED=0));
@WIZSET(SCHEDULED=@WIZEXIST(DATE));

@FMT(CMP,@WIZGET(START)=,,®WIZSET(DATE=®WIZGET(START)));

@WIZINIT;
@WIZDATE(DATE=@DSDF);
@WIZDISPLAY;

@WIZSET(DETAIL=D);
@WIZSET(START=@WIZGET(DATE));
@WIZSET(STOP=@WIZGET(DATE));

@DBVIEW(Q9,
DECLARE @SystemDate DATETIME=GETDATE()
DECLARE @LAST_EXPORT_GL_POST DATETIME=ISNULL((SELECT MAX(TRS.F254) AS F254 FROM TRS_LOG TRS WHERE F990='KDLOC EXPORT GL POSTED'),'01/01/1980')
DECLARE @SMSSCRIPT NVARCHAR(MAX)=N''
DECLARE @F254 DATETIME
DECLARE EXPORT_GL_CUR CURSOR FOR
@FMT(CMP,@WIZGET(SCHEDULED)=0,"SELECT '@WIZGET(DATE)' AS F254","
	SELECT 	DISTINCT F254 
		FROM RPT_FIN
		WHERE F253 BETWEEN @LAST_EXPORT_GL_POST AND @SystemDate
		AND F1031='@WIZGET(DETAIL)'
	UNION 
	SELECT 	DISTINCT F254 
		FROM RPT_DPT
		WHERE F253 BETWEEN @LAST_EXPORT_GL_POST AND @SystemDate
		AND F1031='@WIZGET(DETAIL)'")
OPEN EXPORT_GL_CUR
FETCH NEXT FROM EXPORT_GL_CUR INTO @F254
WHILE @@FETCH_STATUS = 0
BEGIN
	SET @SMSSCRIPT=@SMSSCRIPT+
	N'©MACSHORT(WIZRESET);'+
	'@FMT(CMP,@WIZGET(ONEFILE)=1,"©MACSIL(CREATE TABLE TMP_GL_PostAllStore_OneFile (®DBDCT(F1000,F254,F1033,F01,F1034,F1039,F1130,F1253,F1301,F1302)))");'+
	'©WIZRPL(START='+CONVERT(NVARCHAR(19),@F254,101)+');'+
	'©WIZRPL(STOP='+CONVERT(NVARCHAR(19),@F254,101)+');'+
	'©WIZRPL(DETAIL=@WIZGET(DETAIL));'+	
	'©WIZRPL(OUTPUT=DBT\EXP_ALLTMP@TER.SQI);'+
	'©WIZRPL(ONEFILE=@WIZGET(ONEFILE));'+
	'©WIZRPL(INCLUDEPOSTED=@WIZGET(INCLUDEPOSTED));'+
	'©WIZRPL(STYLE=TXT);'+
	'©EXEC(CGI=trs_exp_gl_post_all_store);'+
	'©EXEC(SQI=©WIZGET(OUTPUT));'
	FETCH NEXT FROM EXPORT_GL_CUR INTO @F254
END
CLOSE EXPORT_GL_CUR
DEALLOCATE EXPORT_GL_CUR
SELECT REPLACE(@SMSSCRIPT,'©','@') AS F3008,@FMT(CMP,@WIZGET(SCHEDULED)=1,"CONVERT(VARCHAR,@SystemDate,27)","'NULL'") AS F1401);

@MACSIL(@DBROW(Q9,F3008,RAW));

INSERT INTO TRS_LOG (F254,F990) 
SELECT '@DBROW(Q9,F1401)' AS F254,'KDLOC EXPORT GL POSTED' AS F990
WHERE '@DBROW(Q9,F1401)'<>'NULL';
