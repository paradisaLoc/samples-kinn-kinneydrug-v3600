/* 10.Daily Flash Report */
/* 30.Custom */

@wizset(TITLE=Flash Report - Daily);
@wizset(HEIGHT=720);
@wizset(WIDTH=1020);

/* SET DEFAULT VARIABLE VALUE */
@WIZSET(DATE=@DSWF);
@WIZRPL(DATE=@DATE(@WIZGET(DATE),DSWF));
@WIZRPL(LYDATE=@DBSELECT(SELECT CONVERT(VARCHAR,DATEADD(YY,-1,'@WIZGET(DATE)'),101)));

/* BUILD HORIZONTAL REPORT TABLE */
@WIZRPL(SESSION=@STORE@TER@FMT(R2,@dbHot(regGen,TMPDB,1,30)));

CREATE TABLE TMP_@WIZGET(SESSION) (@DBDCT(F1056,F1034,F1301,F1302,F1303,F1304,F1305,F1306,F1307,F1311,F1312,F1313,F1314,F1315,F1316,F1317))

@INSERT_HOR(HOR=TMP_@WIZGET(SESSION),KEY=F1056;F1034
,SET=F1301;D@DATE(@WIZGET(DATE),DID-D6F);F1301
,SET=F1302;D@DATE(@WIZGET(DATE),DID-D5F);F1301
,SET=F1303;D@DATE(@WIZGET(DATE),DID-D4F);F1301
,SET=F1304;D@DATE(@WIZGET(DATE),DID-D3F);F1301
,SET=F1305;D@DATE(@WIZGET(DATE),DID-D2F);F1301
,SET=F1306;D@DATE(@WIZGET(DATE),DID-D1F);F1301
,SET=F1307;D@DATE(@WIZGET(DATE),DIDF);F1301
,SET=F1311;D@DATE(@WIZGET(LYDATE),DID-D6F);F1301
,SET=F1312;D@DATE(@WIZGET(LYDATE),DID-D5F);F1301
,SET=F1313;D@DATE(@WIZGET(LYDATE),DID-D4F);F1301
,SET=F1314;D@DATE(@WIZGET(LYDATE),DID-D3F);F1301
,SET=F1315;D@DATE(@WIZGET(LYDATE),DID-D2F);F1301
,SET=F1316;D@DATE(@WIZGET(LYDATE),DID-D1F);F1301
,SET=F1317;D@DATE(@WIZGET(LYDATE),DIDF);F1301,SRC=
SELECT F254,F1056,F1034,SUM(F65) AS F1301 
FROM RPT_FIN 
WHERE (F254 BETWEEN DATEADD(DD,-6,'@WIZGET(DATE)') AND '@WIZGET(DATE)' OR F254 BETWEEN DATEADD(DD,-6,'@WIZGET(LYDATE)') AND '@WIZGET(LYDATE)') AND F1031='D' AND F1034=3
GROUP BY F1056,F1034,F254
UNION
SELECT F254,F1056,F1034,SUM(F64) AS F1301 
FROM RPT_FIN 
WHERE (F254 BETWEEN DATEADD(DD,-6,'@WIZGET(DATE)') AND '@WIZGET(DATE)' OR F254 BETWEEN DATEADD(DD,-6,'@WIZGET(LYDATE)') AND '@WIZGET(LYDATE)') AND F1031='D' AND F1034=2
GROUP BY F1056,F1034,F254);

@WIZSET(Form=NEWFORM);
@EXEC(@FMT(CMP,@WIZGET(OUTPUT)=,HTT,CGI)=Script\cub_KDLOC_daily_flash_rpt);

