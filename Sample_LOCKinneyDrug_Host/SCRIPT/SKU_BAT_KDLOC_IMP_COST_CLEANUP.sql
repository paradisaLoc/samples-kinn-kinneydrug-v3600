/* Kinney Obsolete Cost Cleanup */
@WIZRPL(BATCH=@DBGEN(F902,1));
@WIZRPL(DBASE_TIMEOUT=E);

WITH NEWEST_VENDOR (F1000,F01,F27,F1184,RANK)
AS
(
SELECT COS.F1000,COS.F01,COS.F27,COS.F1184,ROW_NUMBER() OVER(PARTITION BY COS.F1000,COS.F01 ORDER BY VND.F01 DESC,COS.F90 DESC,COS.F39 DESC) AS RANK 
FROM COST_TAB COS
LEFT JOIN KINNEY_VND_STORE_ITEM VND ON COS.F01=VND.F01 AND COS.F27=VND.F27 AND COS.F1000=VND.F1056
)
INSERT INTO FCOST_BAT (F01,F902,F1000,F27,F1184)
SELECT F01,'@WIZGET(BATCH)',F1000,F27,F1184 FROM NEWEST_VENDOR WHERE RANK<>1

IF EXISTS (SELECT * FROM FCOST_BAT WHERE F902='@WIZGET(BATCH)')
INSERT INTO HEADER_BAT (F902,F903,F901,F909,F910,F912,F913,F914,F916)
VALUES ('@WIZGET(BATCH)','LOCAL','LM','@DSDF','0000','REMOVE','AUTO PURGE VENDORS','WAIT','FCOST_BAT')

WITH NEWEST_VENDOR (F1000,F01,F27,F1184,RANK)
AS
(
SELECT COS.F1000,COS.F01,COS.F27,COS.F1184,ROW_NUMBER() OVER(PARTITION BY COS.F1000,COS.F01 ORDER BY VND.F01 DESC,COS.F90 DESC,COS.F39 DESC) AS RANK 
FROM COST_TAB COS
LEFT JOIN KINNEY_VND_STORE_ITEM VND ON COS.F01=VND.F01 AND COS.F27=VND.F27 AND COS.F1000=VND.F1056
)
UPDATE COST_TAB SET F90=1,F1001=1 FROM COST_TAB COS 
JOIN NEWEST_VENDOR NEW ON COS.F1000=NEW.F1000 AND COS.F01=NEW.F01 AND COS.F27=NEW.F27 AND COS.F1184=NEW.F1184 
WHERE RANK=1 AND
ISNULL(COS.F90,'1')<>'1'

@WIZCLR(DBASE_TIMEOUT);
