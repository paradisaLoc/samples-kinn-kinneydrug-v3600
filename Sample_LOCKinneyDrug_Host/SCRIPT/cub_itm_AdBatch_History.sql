CREATE TABLE TMP_@WIZGET(SESSION) (F01 CHAR(13) NOT NULL, 
F29 CHAR(20),
F902 CHAR(8) NOT NULL, DITTO VARCHAR(10), 
F222 CHAR(12), F909 DATE(7), 
F907 DATE(7), F135 NUMERIC(3), 
F136 NUMERIC(7,2), F30 NUMERIC(6,2), 
F1301 NUMBER(10,4), F1302 NUMBER(10,4), 
PRIMARY KEY (F01,F902));

INSERT INTO TMP_@WIZGET(SESSION) (F01,F29,F902,DITTO,F222,F909,F907,F135,F136,F30,F1301,F1302)
SELECT OBJ.F01
              ,MAX(OBJ.F29) AS F29              
              ,ISNULL(BAT.F902,'') AS F902
              ,MAX(BAT.DITTO) AS DITTO
              ,MAX(BAT.F222) AS F222
              ,MAX(BAT.F909) AS F909
              ,MAX(BAT.F907) AS F907
              ,MAX(BAT.F135) AS F135
              ,MAX(BAT.F136) AS F136
              ,MAX(PRI.F30) AS F30
              ,MAX(FCAST.F64) AS F1301
              ,SUM(RPT.F64) AS F1302
              FROM OBJ_TAB OBJ
			  LEFT OUTER JOIN (
				SELECT DISTINCT ALLOW_BAT.F01,ALLOW_BAT.F222,FSPRICE_BAT.F135, FSPRICE_BAT.F136,FSPRICE_BAT.F126,FSPRICE_BAT.F1000,
				 HEADER_BAT.F902,SUBSTRING(HEADER_BAT.F913,1,CHARINDEX('-',HEADER_BAT.F913)-1) AS DITTO,HEADER_BAT.F909,HEADER_BAT.F907 
				FROM HEADER_BAT 
				LEFT OUTER JOIN ALLOW_BAT ON ALLOW_BAT.F902=HEADER_BAT.F902
				LEFT OUTER JOIN FSPRICE_BAT ON FSPRICE_BAT.F902=HEADER_BAT.F902	AND ALLOW_BAT.F01=FSPRICE_BAT.F01
				WHERE CHARINDEX('-',HEADER_BAT.F913)>0 AND (ALLOW_BAT.F01 IN (@DBHOT(SUBQUERY)) OR FSPRICE_BAT.F01 IN (@DBHOT(SUBQUERY)))
				UNION
				SELECT DISTINCT OALLOW_BAT.F01,OALLOW_BAT.F222,OSPRICE_BAT.F135, OSPRICE_BAT.F136,OSPRICE_BAT.F126,OSPRICE_BAT.F1000,
				 HEADER_OLD.F902,SUBSTRING(HEADER_OLD.F913,1,CHARINDEX('-',HEADER_OLD.F913)-1) AS DITTO,HEADER_OLD.F909,HEADER_OLD.F907 
				FROM HEADER_OLD 
				LEFT OUTER JOIN OALLOW_BAT ON OALLOW_BAT.F902=HEADER_OLD.F902
				LEFT OUTER JOIN OSPRICE_BAT ON OSPRICE_BAT.F902=HEADER_OLD.F902	AND OALLOW_BAT.F01=OSPRICE_BAT.F01
				WHERE CHARINDEX('-',HEADER_OLD.F913)>0  AND (OALLOW_BAT.F01 IN (@DBHOT(SUBQUERY)) OR OSPRICE_BAT.F01 IN (@DBHOT(SUBQUERY)))
				) BAT ON BAT.F01=OBJ.F01
              LEFT OUTER JOIN PRICE_TAB PRI ON PRI.F01=BAT.F01 AND PRI.F126=BAT.F126 AND PRI.F1000=BAT.F1000
              LEFT OUTER JOIN RPT_ITM_D RPT ON OBJ.F01=RPT.F01 AND RPT.F1034=3 AND RPT.F254 BETWEEN BAT.F909 AND BAT.F907
              LEFT OUTER JOIN RPT_ITM_D FCAST ON OBJ.F01=FCAST.F01 AND FCAST.F1034=3710 AND FCAST.F254 BETWEEN BAT.F909 AND BAT.F907
              WHERE OBJ.F01 IN (@DBHOT(SUBQUERY)) AND ISNULL(DITTO,'')!=''
              GROUP BY OBJ.F01,BAT.F902 ORDER BY F909 DESC;

