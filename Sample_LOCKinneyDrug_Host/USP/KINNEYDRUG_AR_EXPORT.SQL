IF ((SELECT OBJECT_ID('KINNEYDRUG_AR_EXPORT')) IS NOT NULL) 
DROP PROCEDURE KINNEYDRUG_AR_EXPORT
go

CREATE PROCEDURE KINNEYDRUG_AR_EXPORT
AS
BEGIN
	DECLARE @MyCursor CURSOR
	DECLARE @F254 DATETIME
	DECLARE @F1056 VARCHAR(10)
	DECLARE @F1057 VARCHAR(10)
	DECLARE @F1032 INTEGER
	DECLARE @F1036 VARCHAR(10)
	DECLARE @F1148 VARCHAR(20)
	DECLARE @F65 MONEY
	DECLARE @F65U MONEY
	DECLARE @F1034 INTEGER
	DECLARE @F1101 INTEGER
	DECLARE @F1063 INTEGER
	DECLARE @F1079 VARCHAR(500)

	DECLARE @O254 DATETIME
	DECLARE @O1056 VARCHAR(10)
	DECLARE @O1057 VARCHAR(10)
	DECLARE @O1032 INTEGER

	DECLARE @T201 MONEY

	SET @MyCursor=CURSOR FOR SELECT 
			TRS.F254,TRS.F1056,TRS.F1057,TRS.F1032,TRS.F1036,TRS.F1148,TRS.F65,TND.F65 as F65U,
			F1034=CASE TRS.F1034 WHEN 1206 THEN 0 ELSE 1 END,TND.F1101,TND.F1034 as F1063,TND.F1079
		FROM KINNEY_AR_TRS TRS 
		LEFT OUTER JOIN (
			SELECT F254,F1056,F1057,F1032,F1101,SUM(F65) as F65,MAX(F1034) as F1034,MAX(ISNULL(F1079,'')) as F1079 
			FROM KINNEY_AR_TRS 
			WHERE F1765 IS NULL AND F1034 BETWEEN 100 AND 199
			GROUP BY F254,F1056,F1057,F1032,F1101) TND 
			ON TND.F254=TRS.F254 AND TND.F1056=TRS.F1056 AND TND.F1057=TRS.F1057 AND TND.F1032=TRS.F1032 AND TRS.F1034=201
		WHERE TRS.F1765 IS NULL AND TRS.F1034 IN (201,1206)
		ORDER BY TRS.F254,TRS.F1056,TRS.F1057,TRS.F1032,TND.F1034 DESC

	OPEN @MyCursor 
	FETCH NEXT FROM @MyCursor 
	INTO @F254,@F1056,@F1057,@F1032,@F1036,@F1148,@F65,@F65U,@F1034,@F1101,@F1063,@F1079

	DECLARE @Tenders TABLE (F254 DATETIME,F1056 VARCHAR(10),F1057 VARCHAR(10),F1032 INTEGER,F1036 VARCHAR(10),F1148 VARCHAR(20),F65 MONEY,F1034 INTEGER,F1101 INTEGER,F1063 INTEGER,F1079 VARCHAR(500))

	WHILE @@FETCH_STATUS=0 
	BEGIN
		IF (@F254!=isnull(@O254,GetDate()) OR @F1056!=isnull(@O1056,'') OR @F1057!=isnull(@O1057,'') OR @F1032!=isnull(@O1032,0) OR isnull(@T201,0)=0)
		BEGIN
			SET @O254=@F254
			SET @O1056=@F1056
			SET @O1057=@F1057
			SET @O1032=@F1032
			SET @T201=@F65
		END

		IF abs(@T201)>abs(@F65U)
		BEGIN
			INSERT INTO @Tenders VALUES(@F254,@F1056,@F1057,@F1032,@F1036,@F1148,@F65U,@F1034,@F1101,@F1063,@F1079)
			SET @T201=@T201-@F65U
		END
		ELSE
		IF abs(@T201)>0
		BEGIN
			INSERT INTO @Tenders VALUES(@F254,@F1056,@F1057,@F1032,@F1036,@F1148,@T201,@F1034,@F1101,@F1063,@F1079)
			SET @T201=0
		END

		FETCH NEXT FROM @MyCursor 
		INTO @F254,@F1056,@F1057,@F1032,@F1036,@F1148,@F65,@F65U,@F1034,@F1101,@F1063,@F1079
	END

	CLOSE @MyCursor
	DEALLOCATE @MyCursor
	SELECT F254,F1056,F1057,F1032,F1036,F1148,F65=CASE WHEN F1034=1 THEN -F65 ELSE F65 END,F1034,F1101,F1063,F1079 FROM @Tenders
END
go
