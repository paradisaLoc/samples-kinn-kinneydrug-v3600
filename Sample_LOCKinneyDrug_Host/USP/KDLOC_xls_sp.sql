/* NY QRTRLY CIGARETTE REPORT */
IF ((SELECT OBJECT_ID('KDLOC_NYQRTRLYCIGARETTE_xsl')) IS NOT NULL) 
DROP PROCEDURE KDLOC_NYQRTRLYCIGARETTE_xsl;
GO

CREATE PROCEDURE KDLOC_NYQRTRLYCIGARETTE_xsl (
	@START DATETIME=NULL,
	@STOP DATETIME=NULL,
	@TARGET VARCHAR(5)=NULL
)
AS
BEGIN
	SELECT TOP 5000
	YEAR(RPT.F254) AS D_Year,MONTH(RPT.F254) AS D_Month,RPT.F1056 AS Store,'15-0358720' AS TaxID,MAX(STD.F1531) StoreName,
	SUM(CASE WHEN F04=201 THEN RPT.F65 ELSE 0 END) AS CigSales,
	SUM(CASE WHEN F04 in (202,203,204,205,208,209) THEN RPT.F65 ELSE 0 END) AS TobSales,
	SUM(RPT.F65) AS TotalSales,
	MAX(STD.F1532) AS StrAddress,	MAX(STD.F1534)+' '+MAX(STD.F1549)+' '+MAX(STD.F1535) AS StrCtyST,'20 E. MAIN STREET' AS BillingAddress,
	'Gouverneur, NY 13642' AS BillingCitySt,'315-287-1500' AS Phone
	FROM RPT_ITM_D RPT
	JOIN (SELECT F01,MAX(F04) AS F04 FROM POS_TAB GROUP BY F01) POS ON RPT.F01=POS.F01
	LEFT OUTER JOIN STD_TAB STD ON RPT.F1056=STD.F1056
        JOIN LNK_TAB LNK ON RPT.F1056=LNK.F1056 and RPT.F1057=LNK.F1057 and LNK.F1000=@TARGET
	WHERE F254 BETWEEN @START and @STOP AND POS.F04 in (201,202,203,204,205,208,209)
	GROUP BY YEAR(RPT.F254),MONTH(RPT.F254),RPT.F1056
	ORDER BY RPT.F1056,D_YEAR,D_MONTH
END;
GO

/* TAXABLE SALES */
IF ((SELECT OBJECT_ID('KDLOC_TAXABLESALES_xsl')) IS NOT NULL) 
DROP PROCEDURE KDLOC_TAXABLESALES_xsl;
GO

CREATE PROCEDURE KDLOC_TAXABLESALES_xsl (
	@START DATETIME=NULL,
	@STOP DATETIME=NULL,
	@TARGET VARCHAR(5)=NULL,
	@DETAIL VARCHAR(1)=NULL
)
AS
BEGIN
	SELECT TOP 5000
	RPT.F1056 AS Store,
	SUM(CASE WHEN RPT.F1034 in (21,29,33) THEN RPT.F65 ELSE 0 END) AS TaxableSales,
	SUM(CASE WHEN RPT.F1034=25 THEN RPT.F65 ELSE 0 END) AS TaxableSalesClothing
	FROM RPT_FIN RPT
        JOIN LNK_TAB LNK ON RPT.F1056=LNK.F1056 and RPT.F1057=LNK.F1057 and LNK.F1000=@TARGET
	WHERE F1031=@DETAIL AND F254 BETWEEN @START and @STOP AND RPT.F1034 IN (21,25,29,33)
	GROUP BY RPT.F1056
	ORDER BY RPT.F1056
END;
GO

